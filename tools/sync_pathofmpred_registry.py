#!/usr/bin/env python3
"""Synchronize the controlled analysis registries into PathoFMPred."""
from __future__ import annotations

import csv
import hashlib
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_REGISTRY = ROOT.parent / "TITANPred" / "inst" / "extdata" / "model_registry.csv"
INSTALLED_REGISTRY = ROOT / ".Rlib" / "PathoFMPred" / "extdata" / "model_registry.csv"
SOURCES = (
    ROOT / "models" / "model_registry.csv",
    ROOT / "models" / "foundation_models" / "model_registry_additions.csv",
)
PACKAGE_MODELS = ROOT.parent / "TITANPred" / "inst" / "models"

updates: list[dict[str, str]] = []
update_fields: list[str] = []
source_objects: dict[tuple[str, str], Path] = {}
for source in SOURCES:
    with source.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        source_rows = list(reader)
        for field in reader.fieldnames or []:
            if field not in update_fields:
                update_fields.append(field)
    updates.extend(source_rows)
    source_directory = source.parent
    for row in source_rows:
        model_path = Path(row["file"])
        if not model_path.is_absolute():
            candidate = ROOT / model_path
            model_path = candidate if candidate.is_file() else source_directory / model_path
        source_objects[(row["foundation_model"], row["model_id"])] = model_path

update_keys = [(row["foundation_model"], row["model_id"]) for row in updates]
if len(set(update_keys)) != len(update_keys):
    raise RuntimeError("Duplicate foundation_model/model_id keys in analysis registries")

# Start from the richest existing package registry so metadata generated by
# earlier audit stages is not erased by blank fields in a component registry.
candidates = [p for p in (PACKAGE_REGISTRY, INSTALLED_REGISTRY) if p.is_file()]

def read_registry(path: Path) -> tuple[list[dict[str, str]], list[str]]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        return list(reader), list(reader.fieldnames or [])

def metadata_score(path: Path) -> int:
    existing_rows, _ = read_registry(path)
    wanted = ("screen_balanced_accuracy", "repeated_auc", "primary_estimate_label")
    return sum(bool(row.get(field)) for row in existing_rows for field in wanted)

if candidates:
    base_path = max(candidates, key=metadata_score)
    existing_rows, fields = read_registry(base_path)
else:
    existing_rows, fields = [], []
existing_map = {
    (row["foundation_model"], row["model_id"]): row for row in existing_rows
}

for field in update_fields:
    if field not in fields:
        fields.append(field)
rows: list[dict[str, str]] = []
for update in updates:
    key = (update["foundation_model"], update["model_id"])
    row = dict(existing_map.get(key, {}))
    for field, value in update.items():
        if value not in (None, ""):
            row[field] = value
    sha256 = row.get("sha256", "")
    if len(sha256) != 64:
        raise RuntimeError(f"Invalid model SHA-256 for {row.get('model_id')}")
    # Package objects use content-addressed filenames even when the analysis
    # registries retain descriptive local filenames.
    row["file"] = f"m_{sha256[:24]}.rds"
    rows.append(row)

if len({(r["foundation_model"], r["model_id"]) for r in rows}) != len(rows):
    raise RuntimeError("Duplicate foundation_model/model_id keys in controlled registries")

PACKAGE_REGISTRY.parent.mkdir(parents=True, exist_ok=True)
with PACKAGE_REGISTRY.open("w", newline="", encoding="utf-8") as handle:
    writer = csv.DictWriter(
        handle, fieldnames=fields, extrasaction="ignore", lineterminator="\n"
    )
    writer.writeheader()
    writer.writerows(rows)

# Replace only the generated fitted-object payload. The source package, model
# registry, schemas and documentation remain untouched. Every copied filename
# is content-addressed and its digest is verified against the freshly generated
# analysis registry before it enters the package tree.
for model_name in ("TITAN", "GigaSSL", "ProvGigaPath"):
    destination = PACKAGE_MODELS / model_name
    destination.mkdir(parents=True, exist_ok=True)
    for old_object in destination.glob("*.rds"):
        old_object.unlink()

for row in rows:
    key = (row["foundation_model"], row["model_id"])
    source_object = source_objects.get(key)
    if source_object is None or not source_object.is_file():
        raise RuntimeError(f"Missing fitted object for {key}: {source_object}")
    digest = hashlib.sha256(source_object.read_bytes()).hexdigest()
    if digest != row["sha256"]:
        raise RuntimeError(f"Fitted-object checksum mismatch for {key}")
    destination = PACKAGE_MODELS / row["foundation_model"] / row["file"]
    shutil.copy2(source_object, destination)

print(PACKAGE_REGISTRY)
print(f"Synchronized {len(rows)} verified fitted objects into {PACKAGE_MODELS}")
